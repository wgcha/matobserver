class MatObserverError(Exception):
    """matobserver 공통 예외 기반. code 는 위 상수 중 하나(또는 None)."""

    code: str | None = None

    def __init__(self, message: str = "", *, code: str | None = None) -> None:
        super().__init__(message)
        if code is not None:
            self.code = code


class ConfigError(MatObserverError):
    """설정 파일·환경변수 오류 (키 모름, 타입 불일치 등)."""


class RegistryError(MatObserverError):
    """plugins.d 로딩·검사 실패 — 기동 실패 사유 (중복, 클래스 불일치 등)."""


class UnknownPluginError(MatObserverError):
    """요청한 (type, name)이 미등록 또는 enabled:false. code 는 `*_UNKNOWN`."""

    def __init__(self, message: str, *, plugin_type: str, name: str, disabled: bool = False) -> None:
        super().__init__(message, code=UNKNOWN_PLUGIN_CODE.get(plugin_type))
        self.plugin_type = plugin_type
        self.name = name
        self.disabled = disabled


class UnitError(MatObserverError, ValueError):
    """모르는 물리량 이름 등 단위 변환 오류."""


class EngineFailure(MatObserverError):
    """run_calibration 실패 (module-boundaries.md §4.1). code 는 JOB_ERROR_CODES(api.md §7.3) 중 하나."""

    def __init__(self, code: str, message: str = "") -> None:
        if code not in JOB_ERROR_CODES:
            raise ValueError(f"EngineFailure code must be one of api.md §7.3 job error codes: {code!r}")
        super().__init__(message or code, code=code)


class IncompatibleMaterial(MatObserverError):
    """SolverAdapter.prepare: 지원하지 않는 NeutralMaterial.extensions 키 (plugins.md §4.2)."""


class IncompatibleOverride(MatObserverError):
    """SolverAdapter.prepare: RunOverrides.forbid_mass_scaling 인데 제어 파일에 DT2MS≠0 (plugins.md §4.2)."""
